// Copies the real course syllabus from the student app into the marketing site.
//
//   node scripts/sync-syllabus.mjs [path-to-skillofied-app]
//
// Each app course page exports a SYLLABUS array (module → lessons). This reads
// those files as text, keeps the teaching content — lessons and projects — and
// drops the app-only plumbing: overview pages, quizzes, assignments, exercises,
// assessments and certificates. The result is written to src/data/syllabus.ts.
// Re-run it whenever a course's syllabus changes in the app.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appDir = resolve(process.argv[2] ?? join(here, '../../skillofied-app'));
const pages = join(appDir, 'src/components/courses');

// Website slug → app course page.
const SOURCES = {
  'java-development': 'JavaCoursePage.tsx',
  frontend: 'FrontendCoursePage.tsx',
  sql: 'SqlCoursePage.tsx',
  golang: 'GolangCoursePage.tsx',
  genai: 'GenAICoursePage.tsx',
  'digital-marketing': 'DigitalMarketingCoursePage.tsx',
  seo: 'SeoCoursePage.tsx',
  testing: 'TestingCoursePage.tsx',
};

// In the app, Full Stack is a bundle that unlocks these courses (see
// CoursesSection.tsx), so its syllabus is theirs, grouped per course.
const FULL_STACK_PARTS = [
  ['Java Development', 'java-development'],
  ['Front-End Technologies', 'frontend'],
  ['Mastering SQL', 'sql'],
  ['GenAI & Forward Deployed Engineering', 'genai'],
];

const SKIP_MODULES = /^(COURSE OVERVIEW|FINAL ASSESSMENT|CERTIFICATION)$/i;
const SKIP_ITEM_ID = /(^overview-|-quiz$|-assignment$|-ex$)/;

const ACRONYMS = new Set(['SQL', 'API', 'APIS', 'HTML', 'CSS', 'JS', 'SEO', 'PPC', 'CRO', 'LLM', 'LLMS', 'LLMOPS',
  'RAG', 'AI', 'ML', 'CI/CD', 'JDBC', 'JVM', 'JDK', 'JRE', 'OOP', 'REST', 'DOM', 'UI', 'UX', 'DBMS', 'RDBMS', 'NOSQL',
  'GENAI', 'FDE', 'HTTP', 'JSON', 'IOS', 'QA', 'DDL', 'DML', 'DQL', 'TCL', 'DCL', 'ACID', 'CTE', 'CTES', 'GD', 'ES', 'JWT', 'CLI', 'GRPC', 'AWS', 'GCP', 'SDK', 'URL', 'CRUD', 'MVC', 'JPA', 'ORM', 'DSA', 'GEO', 'AEO', 'PR']);
const SMALL = new Set(['a', 'an', 'and', 'as', 'at', 'by', 'for', 'in', 'of', 'on', 'or', 'the', 'to', 'vs', 'with']);
const FIXED = { APIS: 'APIs', LLMS: 'LLMs', LLMOPS: 'LLMOps', GENAI: 'GenAI', NOSQL: 'NoSQL', IOS: 'iOS', CTES: 'CTEs', JAVASCRIPT: 'JavaScript', TYPESCRIPT: 'TypeScript', GITHUB: 'GitHub', POSTGRESQL: 'PostgreSQL', MYSQL: 'MySQL', GRPC: 'gRPC', GOLANG: 'Golang', DEVOPS: 'DevOps' };

function titleCase(s) {
  return s.split(/\s+/).map((word, i) => {
    const bare = word.replace(/[^A-Za-z/]/g, '').toUpperCase();
    if (FIXED[bare]) return word.replace(/[A-Za-z/]+/, FIXED[bare]);
    if (ACRONYMS.has(bare)) return word.toUpperCase();
    const lower = word.toLowerCase();
    if (i > 0 && SMALL.has(lower)) return lower;
    // Capitalise each hyphen part: "retrieval-augmented" → "Retrieval-Augmented", "ai-assisted" → "AI-Assisted".
    return lower.replace(/(^|-)([a-z]+)/g, (_, sep, part) =>
      sep + (ACRONYMS.has(part.toUpperCase()) ? part.toUpperCase() : part[0].toUpperCase() + part.slice(1)));
  }).join(' ');
}

function parse(file) {
  const src = readFileSync(join(pages, file), 'utf8');
  const body = src.slice(src.indexOf('SYLLABUS'));
  const modules = [];
  const moduleRe = /title:\s*(['"`])(.*?)\1\s*,\s*items:\s*\[(.*?)\]\s*,?\s*\}/gs;
  for (const [, , rawTitle, items] of body.matchAll(moduleRe)) {
    if (SKIP_MODULES.test(rawTitle.trim())) continue;
    const lessons = [...items.matchAll(/id:\s*['"]([^'"]+)['"]\s*,\s*title:\s*(['"`])(.*?)\2/g)]
      .filter(([, id]) => !SKIP_ITEM_ID.test(id))
      .map(([, , , t]) => t.replace(/^Lesson\s+\d+(\.\d+)*\s+/, '').trim());
    if (lessons.length === 0) continue;
    const m = rawTitle.match(/^MODULE\s+(\d+)\s*:\s*(.*)$/i);
    modules.push(m
      ? { module: `Module ${m[1]}: ${titleCase(m[2])}`, lessons }
      : { module: titleCase(rawTitle), lessons });
  }
  if (modules.length === 0) throw new Error(`no syllabus found in ${file}`);
  return modules;
}

const out = {};
for (const [slug, file] of Object.entries(SOURCES)) out[slug] = parse(file);
out['full-stack'] = FULL_STACK_PARTS.map(([name, slug]) => ({
  module: name,
  lessons: out[slug].filter((m) => m.module.startsWith('Module')).map((m) => m.module.replace(/^Module \d+: /, '')),
}));

const header = `// GENERATED by scripts/sync-syllabus.mjs from the student app's course pages.
// Do not edit by hand — change the syllabus in skillofied-app and re-run the script.

export interface SyllabusModule {
  module: string;
  lessons: string[];
}

export const syllabus: Record<string, SyllabusModule[]> = `;
writeFileSync(join(here, '../src/data/syllabus.ts'), header + JSON.stringify(out, null, 2) + ';\n');
for (const [slug, mods] of Object.entries(out)) {
  console.log(`${slug.padEnd(18)} ${mods.length} modules, ${mods.reduce((n, m) => n + m.lessons.length, 0)} lessons`);
}
